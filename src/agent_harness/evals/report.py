"""Markdown report for an eval run."""

from __future__ import annotations

from .runner import EvalSummary


def render_markdown(summary: EvalSummary, model: str) -> str:
    lines = [
        "# Eval report",
        "",
        f"Model: `{model}`",
        f"Pass rate: **{summary.passed}/{summary.total} ({summary.pass_rate:.0%})**",
        f"Total cost: ${summary.total_cost_usd:.4f} · "
        f"Total latency: {summary.total_latency_s:.1f}s · "
        f"Avg steps/task: {summary.avg_steps:.1f}",
        "",
        "| Task | Result | Steps | Tokens | Latency | Cost | Check |",
        "|------|--------|-------|--------|---------|------|-------|",
    ]
    for r in summary.results:
        mark = "✅" if r.passed else "❌"
        lines.append(
            f"| {r.task_id} | {mark} | {r.steps} | "
            f"{r.prompt_tokens + r.completion_tokens} | {r.latency_s:.1f}s | "
            f"${r.cost_usd:.4f} | {r.check_message} |"
        )
    lines += ["", "_Generated by agent-harness-evals. No LLM judge — every pass is a real assertion._"]
    return "\n".join(lines) + "\n"
